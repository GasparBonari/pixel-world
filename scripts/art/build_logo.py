"""Build the title wordmark and its accessible label from APP_NAME."""

import json
import re
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

APP_NAME = "Earthia"

ROOT = Path(__file__).resolve().parents[2]
FONT = ROOT / "node_modules/@expo-google-fonts/pixelify-sans/700Bold/PixelifySans_700Bold.ttf"
OUT = ROOT / "assets/ui"
TS_OUT = ROOT / "src/data/title-logo.generated.ts"
DENSITIES = {"": 2, "@2x": 4, "@3x": 6}  # device pixels per artwork pixel
MAX_GLYPH_WIDTH = 140  # leaves room for the outline on a 320 pt phone


def wordmark():
    # Measure and draw with FreeType's monochrome mode at the artwork's own resolution.
    # Give short names larger glyphs while keeping the wordmark within the same space.
    name = APP_NAME.upper()
    for size in range(34, 0, -1):
        font = ImageFont.truetype(FONT, size)
        left, top, right, bottom = font.getbbox(name, mode="1")
        if right - left <= MAX_GLYPH_WIDTH:
            break
    mask = Image.new("1", (right - left, bottom - top))
    ImageDraw.Draw(mask).text((-left, -top), name, font=font, fill=1)
    bounds = mask.getbbox()
    if not bounds:
        raise ValueError("The app name must contain visible glyphs")
    return mask.crop(bounds).convert("L")


def render():
    theme = (ROOT / "src/constants/theme.ts").read_text()
    colors = {
        name: re.search(rf"{name}: '(#[0-9A-Fa-f]{{6}})'", theme)[1]
        for name in ("goldLight", "gold", "goldShade", "goldDeep", "navyInk")
    }
    glyphs = wordmark()
    width, height = glyphs.width + 2, glyphs.height + 3
    fill = Image.new("L", (width, height))
    fill.paste(glyphs, (1, 1))
    outline = fill.filter(ImageFilter.MaxFilter(3))
    drop = Image.new("L", (width, height))
    drop.paste(outline, (0, 1))

    image = Image.new("RGBA", (width, height))
    image.paste(colors["goldDeep"], (0, 0, width, height), drop)
    image.paste(colors["navyInk"], (0, 0, width, height), outline)
    bevel = Image.new("RGBA", image.size, colors["gold"])
    draw = ImageDraw.Draw(bevel)
    draw.line((0, 1, width - 1, 1), fill=colors["goldLight"])
    draw.line((0, height - 4, width - 1, height - 4), fill=colors["goldShade"])
    draw.line((0, height - 3, width - 1, height - 3), fill=colors["goldDeep"])
    image.paste(bevel, (0, 0), fill)
    return image


def main():
    image = render()
    OUT.mkdir(parents=True, exist_ok=True)
    for suffix, scale in DENSITIES.items():
        image.resize((image.width * scale, image.height * scale), Image.Resampling.NEAREST).save(
            OUT / f"title-logo{suffix}.png", optimize=True
        )
    TS_OUT.write_text(
        "// Generated by scripts/art/build_logo.py. Do not edit.\n"
        "export const TITLE_LOGO = {\n"
        f"  name: {json.dumps(APP_NAME)},\n"
        f"  width: {image.width},\n"
        f"  height: {image.height},\n"
        "  source: require('@/assets/ui/title-logo.png'),\n"
        "} as const;\n"
    )
    print(f"{APP_NAME}: {image.width}×{image.height} artwork pixels at three densities")


if __name__ == "__main__":
    main()
